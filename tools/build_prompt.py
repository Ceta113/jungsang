    print(f"{out.relative_to(ROOT)}: {n}자 (공백 포함) / 공백 제외 {len(''.join(text.split()))}자 / 줄바꿈 2자로 세면 {n + text.count(chr(10))}자")
    if n > LIMIT:
        print(f"!! {n - LIMIT}자 초과")
    if n < FLOOR:
        print(f"!! {FLOOR - n}자 모자람 (크랙 제출 기준 {FLOOR}자 이상)")


